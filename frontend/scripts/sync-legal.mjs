// Copies the published legal texts from the client's legal package into the
// site tree. The server builds from frontend/ only, so the output files are
// committed; the legal package itself never reaches the server.
//
//   cd clients/sf-sofa/am-site/frontend
//   node scripts/sync-legal.mjs
//
// Run it after every edit of the source files, rebuild, then commit
// src/legal/*.md together with the source change.
//
//   ../../legal/02-politika.md -> src/legal/politika.md
//   ../../legal/03-soglasie.md -> src/legal/soglasie.md        ("# Документ 1")
//                              -> src/legal/soglasie-cookie.md ("# Документ 2")
//
// What is dropped from the sources: the document's own top heading (the page
// renders its H1; the heading goes to frontmatter `title`), and in
// 03-soglasie.md the preamble before "# Документ 1" plus the "# Документ N"
// dividers and the "---" rules between the documents — notes about the file,
// not part of either published consent.
//
// Rendering-only changes, the wording stays as written: links to
// https://am-fabrika.ru/... get a site-relative href (they work before the
// domain is delegated and on any preview host), and consecutive plain lines
// (the request form in the policy appendix) get hard line breaks instead of
// being merged into one paragraph.
//
// The script reports every [[placeholder]] left per file. It does not fail on
// them: the pages refuse to show a text containing "[[" unless the build runs
// with LEGAL_PREVIEW=1 (src/components/LegalDoc.astro). Output depends only on
// the sources, so repeated runs change nothing.

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const LEGAL_DIR = path.resolve(root, '../../legal');
const OUT_DIR = path.join(root, 'src/legal');
const SITE_ORIGIN = 'https://am-fabrika.ru';

function fail(message) {
	console.error(`sync-legal: ${message}`);
	process.exit(1);
}

async function readSource(name) {
	const file = path.join(LEGAL_DIR, name);
	if (!existsSync(file)) {
		fail(`${file} not found. Run this script in the repository checkout; the server has no legal package.`);
	}
	return (await readFile(file, 'utf8')).replace(/^\uFEFF/, '').replace(/\r\n?/g, '\n');
}

function trimBlock(lines) {
	const out = [...lines];
	const isFiller = (l) => l.trim() === '' || /^\s*(-{3,}|\*{3,}|_{3,})\s*$/.test(l);
	while (out.length && isFiller(out[0])) out.shift();
	while (out.length && isFiller(out[out.length - 1])) out.pop();
	return out;
}

// Splits "## Title\n...body" (or "# Title") into the title and the body lines.
function takeTitle(lines, level, where) {
	const block = trimBlock(lines);
	const re = new RegExp(`^#{${level}}\\s+(.+?)\\s*$`);
	const m = block.length ? block[0].match(re) : null;
	if (!m) fail(`${where}: expected a "${'#'.repeat(level)} " heading as the first line, found "${block[0] ?? ''}"`);
	return { title: m[1], body: trimBlock(block.slice(1)) };
}

const FENCE = /^\s{0,3}(`{3,}|~{3,})/;
const BLOCK_START = /^\s{0,3}(#{1,6}\s|>|\||[-*+]\s|\d+[.)]\s|(-{3,}|\*{3,}|_{3,})\s*$)/;

function isPlainLine(line) {
	return line.trim() !== '' && !BLOCK_START.test(line) && !FENCE.test(line) && !/^\s{4,}/.test(line);
}

function linkSiteUrls(line) {
	// Skip URLs that are already a link target or inside <...>.
	const re = new RegExp(`(?<!\\]\\(|<)${SITE_ORIGIN.replace(/[.]/g, '\\.')}((?:/[a-z0-9-]+)*/?)`, 'g');
	return line.replace(re, (url, p) => `[${url}](${p || '/'})`);
}

function renderBody(lines) {
	const out = [];
	let inFence = false;
	for (let i = 0; i < lines.length; i++) {
		let line = lines[i];
		if (FENCE.test(line)) {
			inFence = !inFence;
			out.push(line);
			continue;
		}
		if (inFence) {
			out.push(line);
			continue;
		}
		line = linkSiteUrls(line);
		const next = lines[i + 1];
		if (isPlainLine(line) && next !== undefined && isPlainLine(next) && !/(\\| {2})$/.test(line)) {
			line = `${line.replace(/\s+$/, '')}\\`;
		}
		out.push(line);
	}
	return out.join('\n');
}

function placeholders(text) {
	const found = new Map();
	for (const m of text.matchAll(/\[\[([^\]]*)\]\]/g)) {
		found.set(m[0], (found.get(m[0]) ?? 0) + 1);
	}
	return found;
}

async function writeDoc({ out, source, title, body }) {
	const content = [
		'---',
		`# Generated by scripts/sync-legal.mjs from clients/sf-sofa/legal/${source}.`,
		'# Do not edit by hand: change the source file and run `node scripts/sync-legal.mjs`.',
		`title: ${JSON.stringify(title)}`,
		`source: ${JSON.stringify(source)}`,
		'---',
		'',
		renderBody(body),
		'',
	].join('\n');

	const file = path.join(OUT_DIR, out);
	const previous = existsSync(file) ? await readFile(file, 'utf8') : null;
	const status = previous === content ? 'unchanged' : previous === null ? 'created' : 'updated';
	if (status !== 'unchanged') await writeFile(file, content, 'utf8');

	const left = placeholders(`${title}\n${body.join('\n')}`);
	console.log(`src/legal/${out}: ${status}; ${left.size ? `${left.size} placeholder(s) left:` : 'no placeholders'}`);
	for (const [p, n] of left) console.log(`    ${p}${n > 1 ? `  x${n}` : ''}`);
	return left.size;
}

// 02-politika.md: the whole file, including the appendix.
const politika = takeTitle((await readSource('02-politika.md')).split('\n'), 1, '02-politika.md');

// 03-soglasie.md: two documents, each starting at "# Документ N".
const soglasieLines = (await readSource('03-soglasie.md')).split('\n');
const markers = [];
soglasieLines.forEach((line, i) => {
	const m = line.match(/^#\s+Документ\s+(\d+)\s*$/);
	if (m) markers.push({ n: Number(m[1]), i });
});
const EXPECTED = [
	{ n: 1, out: 'soglasie.md', titleCheck: /^Согласие на обработку персональных данных/i },
	{ n: 2, out: 'soglasie-cookie.md', titleCheck: /cookie/i },
];
if (markers.length !== EXPECTED.length || markers.some((m, k) => m.n !== EXPECTED[k].n)) {
	fail(`03-soglasie.md: expected headings "# Документ 1" and "# Документ 2" in order, found ${markers.map((m) => `"# Документ ${m.n}"`).join(', ') || 'none'}`);
}

const consentDocs = EXPECTED.map((doc, k) => {
	const from = markers[k].i + 1;
	const to = k + 1 < markers.length ? markers[k + 1].i : soglasieLines.length;
	const { title, body } = takeTitle(soglasieLines.slice(from, to), 2, `03-soglasie.md, Документ ${doc.n}`);
	if (!doc.titleCheck.test(title)) {
		fail(`03-soglasie.md, Документ ${doc.n}: title "${title}" does not look like the document for ${doc.out}`);
	}
	return { out: doc.out, source: '03-soglasie.md', title, body };
});

await mkdir(OUT_DIR, { recursive: true });
let total = 0;
total += await writeDoc({ out: 'politika.md', source: '02-politika.md', title: politika.title, body: politika.body });
for (const doc of consentDocs) total += await writeDoc(doc);

if (total) {
	console.log('\nPages with placeholders show "document is being prepared" unless built with LEGAL_PREVIEW=1.');
}
